#!/usr/bin/env node
/**
 * Runs the 100 alert-accuracy scenarios (docs/ALERT_ACCURACY_PLAN.md) and
 * writes docs/SCENARIO_REPORT.md.
 *
 *   npm run scenarios                     # report
 *   npm run scenarios -- --update-baseline  # also record today's results in src/scenarios/baseline.ts
 *   npm run scenarios -- --only A07       # one scenario, with its timeline
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { GROUPS, runScenario, SCENARIOS, type ScenarioResult } from '../src/scenarios/index.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { values } = parseArgs({
  options: { 'update-baseline': { type: 'boolean', default: false }, only: { type: 'string' } },
})

if (values.only) {
  const s = SCENARIOS.find((x) => x.id === values.only)
  if (!s) {
    console.error(`no scenario ${values.only}`)
    process.exit(1)
  }
  const r = runScenario(s)
  console.log(`${s.id} ${r.status.toUpperCase()} — ${s.title}`)
  for (const reason of r.reasons) console.log(`  ✗ ${reason}`)
  console.log(`  timeline: ${r.timeline.join(', ') || '(nothing)'}`)
  process.exit(0)
}

const results = new Map<string, ScenarioResult>(SCENARIOS.map((s) => [s.id, runScenario(s)]))
const count = (ids: readonly string[], status: string) => ids.filter((id) => results.get(id)?.status === status).length

const lines: string[] = [
  '# Scenario report',
  '',
  'Generated by `npm run scenarios`. Plan: [ALERT_ACCURACY_PLAN.md](ALERT_ACCURACY_PLAN.md).',
  '',
  '**pass** = the app already does what it should · **fail** = known problem to fix · **clip** = needs a real recorded clip (not run)',
  '',
  '| Group | Pass | Fail | Clip |',
  '| --- | --- | --- | --- |',
]
for (const [key, g] of Object.entries(GROUPS)) {
  const ids = g.scenarios.map((s) => s.id)
  lines.push(`| ${key}. ${g.title} | ${count(ids, 'pass')} | ${count(ids, 'fail')} | ${count(ids, 'clip')} |`)
}
const all = SCENARIOS.map((s) => s.id)
lines.push(`| **Total** | **${count(all, 'pass')}** | **${count(all, 'fail')}** | **${count(all, 'clip')}** |`, '')

for (const [key, g] of Object.entries(GROUPS)) {
  lines.push(`## ${key}. ${g.title}`, '', '| ID | Result | Scenario | Why it fails / what the app did |', '| --- | --- | --- | --- |')
  for (const s of g.scenarios) {
    const r = results.get(s.id)
    if (!r) continue
    const mark = r.status === 'pass' ? '✅ pass' : r.status === 'fail' ? '❌ fail' : '🎥 clip'
    const detail = r.status === 'fail' ? r.reasons.join('; ') : r.status === 'clip' ? r.reasons.join('; ') : r.timeline.slice(0, 4).join(', ')
    lines.push(`| ${s.id} | ${mark} | ${s.title} | ${detail.replaceAll('|', '/')} |`)
  }
  lines.push('')
}

writeFileSync(join(root, 'docs', 'SCENARIO_REPORT.md'), `${lines.join('\n')}\n`)
console.log(lines.slice(6, 6 + 9).join('\n'))
console.log('\nreport written to docs/SCENARIO_REPORT.md')

if (values['update-baseline']) {
  const entries = SCENARIOS.map((s) => `  ${s.id}: '${results.get(s.id)?.status ?? 'fail'}',`).join('\n')
  const source = [
    '/** Generated by `npm run scenarios -- --update-baseline`. Do not edit by hand. */',
    "import type { ScenarioStatus } from './runner.ts'",
    '',
    'export const BASELINE: Readonly<Record<string, ScenarioStatus>> = {',
    entries,
    '}',
    '',
  ].join('\n')
  writeFileSync(join(root, 'src', 'scenarios', 'baseline.ts'), source)
  console.log('baseline written to src/scenarios/baseline.ts')
}
