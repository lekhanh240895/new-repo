#!/usr/bin/env node
/**
 * Drive check (plan P8) for a saved drive log:
 *
 *   npm run drive-check -- ~/Downloads/biomonitor-drive-2026-11-03.json
 *
 * Prints the GPS and turn-sensor results and writes replay-out/DRIVE_REPORT.md
 * (git-ignored). The log holds only numbers: no position, no images.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { checkDrive, type DriveReport } from '../src/core/drive/check.ts'
import { parseDriveLog } from '../src/core/drive/log.ts'

function fail(message: string): never {
  console.error(`drive-check: ${message}`)
  process.exit(1)
}

const file = process.argv[2]
if (file === undefined) fail('usage: npm run drive-check -- <drive-log.json>')

let data: unknown
try {
  data = JSON.parse(readFileSync(file, 'utf8'))
} catch (err) {
  fail(`cannot read ${file}: ${err instanceof Error ? err.message : String(err)}`)
}
const parsed = parseDriveLog(data)
if ('error' in parsed) fail(`${file}: ${parsed.error}`)

const r: DriveReport = checkDrive(parsed.log)
const min = (sec: number) => `${Math.floor(sec / 60)} min ${Math.round(sec % 60)} s`
const signed = (v: number | null, unit: string) => (v === null ? '—' : `${v > 0 ? '+' : ''}${v.toFixed(0)}${unit}`)

const gyroLine = {
  ok: `✅ OK — keep \`motion.turnRightSign: ${r.gyro.currentSign}\``,
  flip: `❌ reversed — set \`motion.turnRightSign: ${r.gyro.recommendedSign}\` in src/core/config.ts`,
  unclear: '❓ unclear — turns disagree; record another drive',
  notEnough: '❓ not enough clear turns — drive with more corners',
  noSensor: '— no gyroscope data from this phone',
}[r.gyro.verdict]

const lines = [
  '# Drive check',
  '',
  'Generated by `npm run drive-check` (P8). Numbers only: no position, no images.',
  '',
  `- Drive: ${min(r.durationSec)}${r.truncated ? ' (log full: the end is missing)' : ''}`,
  `- GPS speed: **${r.gps.verdict}** — ${Math.round(r.gps.fixRatio * 100)}% of the time, top ${r.gps.maxKmh === null ? '—' : `${Math.round(r.gps.maxKmh)} km/h`}, moving ${min(r.gps.movingSec)}, stopped ${min(r.gps.stoppedSec)}`,
  `- Alarms: ${r.alarms}; started while stopped: ${r.stoppedAlarms.length === 0 ? '✅ none' : `❌ ${r.stoppedAlarms.map((a) => `${a.level} at ${min(a.atSec)}`).join(', ')}`}`,
  `- Turn sensor: ${gyroLine}${r.gyro.source === null ? '' : ` (${r.gyro.agree} agree, ${r.gyro.disagree} disagree, judged by ${r.gyro.source === 'heading' ? 'GPS heading' : 'head yaw — weaker'})`}`,
  '',
  '## Turns',
  '',
  '| At | Length | Gyroscope | GPS heading change | Head yaw |',
  '| --- | --- | --- | --- | --- |',
  ...r.turns.map((t) => `| ${min(t.atSec)} | ${t.durationSec.toFixed(1)} s | ${signed(t.turnRate, '°/s')} | ${signed(t.headingChange, '°')} | ${signed(t.headYaw, '°')} |`),
  ...(r.turns.length === 0 ? ['| — | | | | |'] : []),
  '',
]
const report = lines.join('\n')
console.log(report)
try {
  mkdirSync('replay-out', { recursive: true })
  writeFileSync(join('replay-out', 'DRIVE_REPORT.md'), report)
  console.log('report written to replay-out/DRIVE_REPORT.md')
} catch (err) {
  fail(`cannot write the report: ${err instanceof Error ? err.message : String(err)}`)
}
