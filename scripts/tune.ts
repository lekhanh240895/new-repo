#!/usr/bin/env node
/**
 * Self-improve loop (T13): how far can each config value move before a
 * scenario breaks? Writes docs/TUNING_REPORT.md. Never changes the config:
 * it suggests, a person decides.
 *
 *   npm run tune                          # all tunable values (~5 min)
 *   npm run tune -- --param budgets.lapMs # one value
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { runLibrary, suggest, sweep, TUNABLE, type Sweep } from '../src/scenarios/tuning.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { values } = parseArgs({ options: { param: { type: 'string', multiple: true } } })
const params = values.param ?? [...TUNABLE]
for (const p of params) {
  if (!TUNABLE.includes(p)) {
    console.error(`unknown parameter ${p}. Tunable: ${TUNABLE.join(', ')}`)
    process.exit(1)
  }
}

const base = runLibrary()
console.log(`defaults: ${base.passed.size} pass, ${base.failed.size} fail, ${base.misses.length} must-alarm misses`)
const sweeps: Sweep[] = []
for (const p of params) {
  const s = sweep(p, base)
  sweeps.push(s)
  console.log(`${p.padEnd(30)} safe ×${s.safeLow}–×${s.safeHigh}`)
}

const fmt = (v: number) => (Math.abs(v) >= 100 ? String(Math.round(v)) : String(Math.round(v * 1000) / 1000))
const edge = (s: Sweep, low: boolean) => {
  const side = s.points.filter((p) => (low ? p.factor < 1 : p.factor > 1)).sort((a, b) => (low ? b.factor - a.factor : a.factor - b.factor))
  const first = side.find((p) => p.broken.length > 0)
  return first ? `×${first.factor}: ${first.broken.slice(0, 4).join(', ')}${first.broken.length > 4 ? '…' : ''}` : 'nothing in range'
}
const tips = suggest(sweeps)
const lines = [
  '# Tuning report',
  '',
  'Generated by `npm run tune` (docs/ALERT_ACCURACY_PLAN.md, T13). Each config value is moved',
  'alone; the whole scenario library is replayed for each step.',
  '',
  `Defaults: **${base.passed.size} pass, ${base.failed.size} fail, ${base.misses.length} must-alarm misses**.`,
  '',
  '**Safe range** = the factors around the default where no passing case breaks. A narrow range',
  'means the synthetic cases pin this value tightly; check it first with real clips (P7). The',
  'scenarios are synthetic, so a wide range does not prove the value is right on real faces.',
  '',
  '| Value | Default | Safe range | First break, lower | First break, higher |',
  '| --- | --- | --- | --- | --- |',
  ...sweeps.map((s) => `| \`${s.path}\` | ${fmt(s.value)} | ${fmt(s.value * s.safeLow)}–${fmt(s.value * s.safeHigh)} (×${s.safeLow}–×${s.safeHigh}) | ${edge(s, true)} | ${edge(s, false)} |`),
  '',
  '## Suggestions',
  '',
  ...(tips.length === 0
    ? ['None: no single change passes more cases without breaking one. The defaults stay.']
    : tips.map((x) => `- \`${x.path}\`: ${fmt(x.from)} → ${fmt(x.to)} fixes ${x.fixed.join(', ')} (breaks nothing). Review before applying.`)),
  '',
]
writeFileSync(join(root, 'docs', 'TUNING_REPORT.md'), lines.join('\n'))
console.log('report written to docs/TUNING_REPORT.md')
